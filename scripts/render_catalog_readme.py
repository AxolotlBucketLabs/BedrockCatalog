#!/usr/bin/env python3
"""Render the visual Marketplace catalog from the complete JSON exports."""

from __future__ import annotations

import argparse
import html
import json
from collections import defaultdict
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit


def read_items(path: Path) -> list[dict[str, Any]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    items = payload.get("items") if isinstance(payload, dict) else None
    if not isinstance(items, list):
        raise ValueError(f"{path} does not contain an items array.")
    return [item for item in items if isinstance(item, dict)]


def markdown_cell(value: Any) -> str:
    text = str(value if value is not None else "")
    text = text.replace("\\", "\\\\")
    for character in ("|", "`", "*", "_", "[", "]", "<", ">"):
        text = text.replace(character, f"\\{character}")
    return text.replace("\r", " ").replace("\n", " ")


def image_url(item: dict[str, Any]) -> str | None:
    images = item.get("images")
    if not isinstance(images, list):
        return None
    thumbnails = [
        image
        for image in images
        if (
            isinstance(image, dict)
            and isinstance(image.get("Url"), str)
            and image["Url"]
            and urlsplit(image["Url"]).scheme == "https"
            and urlsplit(image["Url"]).netloc
        )
    ]
    thumbnails.sort(key=lambda image: image.get("Tag") != "Thumbnail")
    return thumbnails[0]["Url"] if thumbnails else None


def render_row(item: dict[str, Any]) -> str:
    thumbnail = image_url(item)
    if thumbnail is None:
        preview = "No thumbnail"
    else:
        safe_url = html.escape(thumbnail, quote=True)
        preview = f'<a href="{safe_url}"><img src="{safe_url}" width="64" alt=""></a>'
    fields = (
        preview,
        markdown_cell(item.get("title") or "Untitled"),
        markdown_cell(item.get("creatorName") or "Unknown"),
        markdown_cell(item.get("uuid") or "Not provided"),
    )
    return "| " + " | ".join(fields) + " |"


def render_table(items: list[dict[str, Any]]) -> list[str]:
    lines = [
        "| Preview | Item | Creator | UUID |",
        "| --- | --- | --- | --- |",
    ]
    lines.extend(render_row(item) for item in items)
    return lines


def render(data_dir: Path) -> str:
    emotes = read_items(data_dir / "persona-emotes.json")
    pieces = read_items(data_dir / "persona-pieces.json")
    pieces_by_type: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for item in pieces:
        piece_type = item.get("pieceType")
        if isinstance(piece_type, str) and piece_type:
            pieces_by_type[piece_type].append(item)

    lines = [
        "<!-- Generated by scripts/render_catalog_readme.py. -->",
        "",
        "# Visual Catalog",
        "",
        "This page shows thumbnails for every exported persona emote and up to three examples for each confirmed persona piece type. The complete records and all persona pieces are available in the [emote JSON](../data/persona-emotes.json) and [persona piece JSON](../data/persona-pieces.json).",
        "",
        "Thumbnails are linked directly from the image URLs supplied in the catalog records.",
        "",
        f"## Persona emotes ({len(emotes):,})",
        "",
    ]
    lines.extend(render_table(sorted(emotes, key=lambda item: (str(item.get("title") or "").casefold(), str(item.get("id") or "")))))
    lines.extend(("", "## Persona pieces", ""))

    for piece_type in sorted(pieces_by_type):
        items = sorted(
            (item for item in pieces_by_type[piece_type] if image_url(item)),
            key=lambda item: (str(item.get("title") or "").casefold(), str(item.get("id") or "")),
        )
        examples = items[:3]
        heading = piece_type.removeprefix("persona_").replace("_", " ").title()
        lines.extend((f"### {heading} ({len(pieces_by_type[piece_type]):,} items)", ""))
        if examples:
            lines.extend(render_table(examples))
        else:
            lines.append("No thumbnail examples are available in the current export.")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=Path("data"), help="Directory containing catalog JSON exports")
    parser.add_argument("--output", type=Path, default=Path("catalog/README.md"), help="README path to write")
    arguments = parser.parse_args()

    content = render(arguments.data_dir)
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
