#!/usr/bin/env python3
"""Render visual Marketplace catalog READMEs from the JSON exports."""

from __future__ import annotations

import argparse
import html
import json
import re
from collections import defaultdict
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit


GENERATED_MARKER = "<!-- Generated by scripts/render_catalog_readme.py. -->"
MAX_PAGE_BYTES = 350 * 1024
PAGE_HEADER_RESERVE_BYTES = 4096
TABLE_HEADER = ("| Preview | Item | Creator | UUID |", "| --- | --- | --- | --- |")


def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def read_items(path: Path) -> list[dict[str, Any]]:
    payload = read_json(path)
    items = payload.get("items") if isinstance(payload, dict) else None
    if not isinstance(items, list):
        raise ValueError(f"{path} does not contain an items array.")
    if any(not isinstance(item, dict) for item in items):
        raise ValueError(f"{path} contains a non-object catalog item.")
    return items


def read_confirmed_piece_types(path: Path) -> list[str]:
    payload = read_json(path)
    datasets = payload.get("datasets") if isinstance(payload, dict) else None
    if not isinstance(datasets, list):
        raise ValueError(f"{path} does not contain a datasets array.")
    for dataset in datasets:
        if isinstance(dataset, dict) and dataset.get("name") == "persona_pieces":
            piece_types = dataset.get("pieceTypes")
            if isinstance(piece_types, list) and all(isinstance(item, str) for item in piece_types):
                return piece_types
            raise ValueError(f"{path} does not contain confirmed persona piece types.")
    raise ValueError(f"{path} does not define the persona_pieces dataset.")


def markdown_cell(value: Any) -> str:
    text = str(value if value is not None else "")
    text = text.replace("\\", "\\\\")
    for character in ("|", "`", "*", "_", "[", "]", "<", ">"):
        text = text.replace(character, f"\\{character}")
    return text.replace("\r", " ").replace("\n", " ")


def image_url(item: dict[str, Any]) -> str | None:
    images = item.get("images")
    if not isinstance(images, list):
        return None
    thumbnails = [
        image
        for image in images
        if (
            isinstance(image, dict)
            and isinstance(image.get("Url"), str)
            and image["Url"]
            and urlsplit(image["Url"]).scheme == "https"
            and urlsplit(image["Url"]).netloc
        )
    ]
    thumbnails.sort(key=lambda image: image.get("Tag") != "Thumbnail")
    return thumbnails[0]["Url"] if thumbnails else None


def render_row(item: dict[str, Any]) -> str:
    thumbnail = image_url(item)
    if thumbnail is None:
        preview = "No thumbnail"
    else:
        safe_url = html.escape(thumbnail, quote=True)
        preview = f'<img src="{safe_url}" width="64" alt="">'
    fields = (
        preview,
        markdown_cell(item.get("title") or "Untitled"),
        markdown_cell(item.get("creatorName") or "Unknown"),
        markdown_cell(item.get("uuid") or "Not provided"),
    )
    return "| " + " | ".join(fields) + " |"


def item_sort_key(item: dict[str, Any]) -> tuple[str, str]:
    return str(item.get("title") or "").casefold(), str(item.get("id") or "")


def display_name(piece_type: str) -> str:
    return piece_type.removeprefix("persona_").replace("_", " ").title()


def directory_name(piece_type: str) -> str:
    slug = piece_type.removeprefix("persona_").replace("_", "-")
    if not re.fullmatch(r"[a-z0-9-]+", slug):
        raise ValueError(f"Unsupported persona piece type name: {piece_type}")
    return slug


def chunk_items(items: list[dict[str, Any]]) -> list[list[dict[str, Any]]]:
    if not items:
        return []
    ordered = sorted(items, key=item_sort_key)
    header_bytes = len(("\n".join(TABLE_HEADER) + "\n").encode("utf-8"))
    content_limit = MAX_PAGE_BYTES - PAGE_HEADER_RESERVE_BYTES
    chunks: list[list[dict[str, Any]]] = []
    current: list[dict[str, Any]] = []
    current_size = header_bytes

    for item in ordered:
        row_size = len((render_row(item) + "\n").encode("utf-8"))
        if row_size + header_bytes > content_limit:
            raise ValueError("A catalog item is too large to fit in a Markdown page.")
        if current and current_size + row_size > content_limit:
            chunks.append(current)
            current = []
            current_size = header_bytes
        current.append(item)
        current_size += row_size

    if current:
        chunks.append(current)
    return chunks


def render_page(
    title: str,
    item_label: str,
    json_link: str,
    items: list[dict[str, Any]],
    item_count: int,
    page_number: int,
    page_count: int,
    first_item_number: int,
) -> str:
    last_item_number = first_item_number + len(items) - 1
    lines = [
        GENERATED_MARKER,
        "",
        f"# {title} (Page {page_number} of {page_count})",
        "",
        f"{item_label} {first_item_number:,} to {last_item_number:,} of {item_count:,}.",
        "",
        f"[JSON data]({json_link}).",
        "",
        *TABLE_HEADER,
    ]
    lines.extend(render_row(item) for item in items)
    content = "\n".join(lines) + "\n"
    if len(content.encode("utf-8")) > MAX_PAGE_BYTES:
        raise ValueError(f"Generated page exceeds the {MAX_PAGE_BYTES:,}-byte size limit.")
    return content


def render_item_catalog(
    title: str,
    item_label: str,
    json_link: str,
    items: list[dict[str, Any]],
    page_dir: Path,
) -> dict[Path, str]:
    chunks = chunk_items(items)
    files: dict[Path, str] = {}
    for page_number, chunk in enumerate(chunks, start=1):
        first_item_number = sum(len(previous) for previous in chunks[: page_number - 1]) + 1
        filename = f"page-{page_number:03}.md"
        files[page_dir / filename] = render_page(
            title,
            item_label,
            json_link,
            chunk,
            len(items),
            page_number,
            len(chunks),
            first_item_number,
        )

    lines = [
        GENERATED_MARKER,
        "",
        f"# {title}",
        "",
        f"{len(items):,} items in {len(chunks)} pages."
        if items
        else "No items are currently exported.",
        "",
        f"[JSON data]({json_link}).",
        "",
        "| Page | Items | Catalog |",
        "| ---: | ---: | --- |",
    ]
    first_item_number = 1
    for page_number, chunk in enumerate(chunks, start=1):
        last_item_number = first_item_number + len(chunk) - 1
        filename = f"page-{page_number:03}.md"
        lines.append(
            f"| {page_number} | {first_item_number:,} to {last_item_number:,} | [Open page](./{filename}) |"
        )
        first_item_number = last_item_number + 1
    lines.append("")
    files[page_dir / "README.md"] = "\n".join(lines)
    return files


def render_catalog(data_dir: Path, config_path: Path) -> dict[Path, str]:
    emotes = read_items(data_dir / "persona-emotes.json")
    pieces = read_items(data_dir / "persona-pieces.json")
    confirmed_types = read_confirmed_piece_types(config_path)
    pieces_by_type: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for item in pieces:
        piece_type = item.get("pieceType")
        if not isinstance(piece_type, str) or not piece_type:
            raise ValueError("A persona piece is missing its piece type.")
        if piece_type not in confirmed_types:
            raise ValueError(f"Unconfirmed persona piece type found: {piece_type}")
        pieces_by_type[piece_type].append(item)

    files: dict[Path, str] = {
        Path("README.md"): "\n".join(
            (
                GENERATED_MARKER,
                "",
                "# Visual Catalog",
                "",
                "Browse the complete thumbnail lists. Each list is split into pages for reliable GitHub rendering.",
                "",
                "- [Persona emotes](persona-emotes/README.md).",
                "- [Persona pieces](persona-pieces/README.md).",
                "",
            )
        ),
    }

    files.update(
        render_item_catalog(
            "Persona Emotes",
            "Items",
            "../../data/persona-emotes.json",
            emotes,
            Path("persona-emotes"),
        )
    )

    index_lines = [
        GENERATED_MARKER,
        "",
        "# Persona Pieces",
        "",
        f"{len(confirmed_types)} confirmed types with {len(pieces):,} items.",
        "",
        "| Type | Items | Catalog |",
        "| --- | ---: | --- |",
    ]
    for piece_type in sorted(confirmed_types):
        slug = directory_name(piece_type)
        name = display_name(piece_type)
        items = pieces_by_type[piece_type]
        index_lines.append(f"| {name} | {len(items):,} | [Browse](./{slug}/README.md) |")
        files.update(
            render_item_catalog(
                name,
                "Items",
                "../../../data/persona-pieces.json",
                items,
                Path("persona-pieces") / slug,
            )
        )
    index_lines.append("")
    files[Path("persona-pieces/README.md")] = "\n".join(index_lines)
    return files


def write_catalog(output_dir: Path, files: dict[Path, str]) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    expected_paths = {output_dir / relative_path for relative_path in files}
    if output_dir.exists():
        for candidate in output_dir.rglob("*.md"):
            if candidate in expected_paths or candidate.is_symlink() or not candidate.is_file():
                continue
            with candidate.open(encoding="utf-8") as generated_file:
                if generated_file.readline().rstrip("\r\n") == GENERATED_MARKER:
                    candidate.unlink()

    for relative_path, content in files.items():
        output_path = output_dir / relative_path
        if output_path.is_symlink():
            raise ValueError(f"Refusing to overwrite symlink: {output_path}")
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(content, encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=Path("data"), help="Directory containing catalog JSON exports")
    parser.add_argument("--config", type=Path, default=Path("config/confirmed-types.json"), help="Confirmed catalog type configuration")
    parser.add_argument("--output-dir", type=Path, default=Path("catalog"), help="Directory for generated README files")
    arguments = parser.parse_args()

    files = render_catalog(arguments.data_dir, arguments.config)
    write_catalog(arguments.output_dir, files)
    pages = sum(path.name.startswith("page-") for path in files)
    print(f"Generated {len(files)} README and catalog page files across {pages} thumbnail pages.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
